from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class CompileRequest(BaseModel):
    code: str = Field(..., description="Raw Mojo source code")
    flags: List[str] = Field(default_factory=list, description="Optimization flags like --unroll, --vectorize")
    opt_level: Optional[str] = Field(default="-O3", description="Optimization level (-O0, -O1, -O2, -O3)")


class CompileResponse(BaseModel):
    mlir: str = Field(..., description="Compiled MLIR / IR text output")
    dialect_info: Dict[str, Any] = Field(default_factory=dict, description="Dialect metrics and detected operations")
    compiler_diagnostics: str = Field(default="", description="Compiler output or diagnostics")
    duration_ms: float = Field(..., description="Compilation time in milliseconds")
    success: bool = Field(default=True, description="Whether compilation succeeded")


class ExecuteRequest(BaseModel):
    code: str = Field(..., description="Raw source code to execute")
    runtime: str = Field(default="mojo", description="Target runtime ('mojo' or 'python')")
    stdin: Optional[str] = Field(default="", description="Standard input to inject into the process")


class ExecuteResponse(BaseModel):
    stdout: str = Field(..., description="Captured standard output")
    stderr: str = Field(..., description="Captured standard error")
    exit_code: int = Field(..., description="Process exit return code")
    execution_time_ms: float = Field(..., description="Execution duration in milliseconds")
    runtime: str = Field(..., description="Runtime used for execution")


class MetricSet(BaseModel):
    latency_ms: float = Field(..., description="Execution latency in milliseconds")
    peak_memory_mb: float = Field(..., description="Peak Resident Set Size (RSS) in Megabytes")
    cpu_utilization_pct: float = Field(..., description="CPU utilization percentage during execution")
    stdout: str = Field(default="", description="Console output")
    exit_code: int = Field(default=0, description="Exit code")


class BenchmarkRequest(BaseModel):
    python_code: str = Field(..., description="Python kernel implementation to benchmark")
    mojo_code: str = Field(..., description="Mojo kernel implementation to benchmark")
    stdin: Optional[str] = Field(default="", description="Optional runtime input for both benchmarks")
    runs: int = Field(default=3, description="Number of benchmark iterations to average")


class BenchmarkResponse(BaseModel):
    python: MetricSet = Field(..., description="Python execution metrics")
    mojo: MetricSet = Field(..., description="Mojo execution metrics")
    speedup_factor: float = Field(..., description="Speedup multiplier (Python latency / Mojo latency)")
    memory_delta_mb: float = Field(..., description="Difference in peak memory usage in MB")
    cpu_delta_pct: float = Field(..., description="Difference in CPU utilization percentage")


class ModelLayerInfo(BaseModel):
    name: str
    op_type: str
    inputs: List[str]
    outputs: List[str]
    shape: Optional[List[int]] = None


class ModelIngestResponse(BaseModel):
    filename: str = Field(..., description="Name of the uploaded model file")
    format: str = Field(..., description="Detected format ('onnx' or 'pytorch')")
    layer_count: int = Field(..., description="Number of computational nodes / layers")
    layers: List[ModelLayerInfo] = Field(default_factory=list, description="Extracted layer details")
    input_shape: List[int] = Field(default_factory=list, description="Primary model input shape")
    output_shape: List[int] = Field(default_factory=list, description="Primary model output shape")
    mlir: str = Field(..., description="Structural MLIR generated by MAX Engine")
    success: bool = Field(default=True, description="Whether ingestion and compilation succeeded")
